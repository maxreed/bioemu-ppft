class StructureLibrary:
    """
    For loading CA positions (nm) and backbone orientation frames
    from a pre-generated XTC ensemble (made by BioEmu v1.1).

    Orientations are (3,3) rotation matrices per residue constructed from
    N, CA, C backbone atoms using Gram-Schmidt orthogonalisation, matching
    the OpenFold backbone rigid frame convention that BioEmu uses:
        origin: CA
        e1 (x): normalise(CA - N)   i.e. N -> CA direction
        e2 (y): component of (C - CA) orthogonal to e1, normalised
        e3 (z): e1 x e2  (right-hand rule)
        R = [e1 | e2 | e3]  (columns)

    Reference: openfold/utils/rigid_utils.py Rigid.make_transform_from_reference,
    which is what convert_chemgraph.py uses via get_atom37_from_frames.
    """

    def __init__(self, xtc_path: Path, pdb_path: Path):
        traj = mdtraj.load(str(xtc_path), top=str(pdb_path))
        top = traj.topology

        # Select backbone atom indices in residue order
        ca_indices = []
        n_indices = []
        c_indices = []
        for residue in top.residues:
            ca = n = c = None
            for atom in residue.atoms:
                if atom.name == "CA":
                    ca = atom.index
                elif atom.name == "N":
                    n = atom.index
                elif atom.name == "C":
                    c = atom.index
            if ca is None or n is None or c is None:
                raise ValueError(
                    f"Residue {residue} is missing N, CA, or C atoms in {pdb_path}. "
                    f"Cannot construct backbone frames."
                )
            ca_indices.append(ca)
            n_indices.append(n)
            c_indices.append(c)

        ca_indices = np.array(ca_indices)
        n_indices = np.array(n_indices)
        c_indices = np.array(c_indices)

        # xyz in nm: shape (n_frames, n_residues, 3)
        pos_ca = traj.xyz[:, ca_indices, :]
        pos_n  = traj.xyz[:, n_indices,  :]
        pos_c  = traj.xyz[:, c_indices,  :]

        # Zero-centre CA positions per frame (BioEmu prior is zero-mean).
        # This is not required for the current setup, but I'll keep in case I generalize this function to
        # take in any set of inputs (which may not be centered at the origin), not just BioEmu trajectories.
        pos_ca -= pos_ca.mean(axis=1, keepdims=True)

        # Build local frames via Gram-Schmidt: (n_frames, n_residues, 3, 3)
        # OpenFold convention: e1 = N->CA, e2 = orthogonalised CA->C, e3 = e1 x e2
        def normalise(v):
            return v / (np.linalg.norm(v, axis=-1, keepdims=True) + 1e-8)

        e1 = normalise(pos_ca - pos_n)                         # N -> CA (x-axis)
        v  = pos_c - pos_ca                                    # CA -> C
        e2 = normalise(v - (v * e1).sum(axis=-1, keepdims=True) * e1)  # orthogonalised (y-axis)
        e3 = np.cross(e1, e2)                                  # right-hand z-axis

        # Stack as columns: shape (n_frames, n_residues, 3, 3)
        frames = np.stack([e1, e2, e3], axis=-1)

        self.positions_nm  = pos_ca.astype(np.float32)   # (n_frames, n_residues, 3)
        self.orientations  = frames.astype(np.float32)   # (n_frames, n_residues, 3, 3)
        self.n_frames = self.positions_nm.shape[0]
        logger.debug(
            f"Loaded {self.n_frames} frames from {xtc_path} "
            f"with {self.positions_nm.shape[1]} residues."
        )

    def sample(self, rng: np.random.Generator | None = None) -> tuple[np.ndarray, np.ndarray]:
        """Return a randomly sampled frame as ((n_residues, 3), (n_residues, 3, 3)) in nm."""
        idx = (rng or np.random.default_rng()).integers(self.n_frames)
        return self.positions_nm[idx], self.orientations[idx]


# Module-level cache so we don't reload XTC files on every step
_structure_library_cache: dict[str, StructureLibrary] = {}


def get_structure_library(xtc_path: Path, pdb_path: Path) -> StructureLibrary:
    key = str(xtc_path)
    if key not in _structure_library_cache:
        _structure_library_cache[key] = StructureLibrary(xtc_path, pdb_path)
    return _structure_library_cache[key]


def compute_dsm_loss(
    score_model: torch.nn.Module,
    sdes: dict[str, SDE],
    x0_pos_nm: torch.Tensor,            # (n_residues, 3) in nm, on device
    x0_orientations: torch.Tensor,      # (n_residues, 3, 3) rotation matrices, on device
    context_chemgraph: ChemGraph,
    device: torch.device,
) -> torch.Tensor:
    """
    Denoising Score Matching loss for a single example structure.

    Given x0 positions and backbone orientation frames extracted from the XTC:
      1. Sample a random noise level t ~ Uniform(0.05, 0.99).
      2. Corrupt x0 positions via the forward VP-SDE: x_t = alpha_t * x0 + sigma_t * eps.
      3. Corrupt x0 orientations via the forward SO3-SDE: R_t = R_0 @ IGSO3(I, sigma_rot_t).
      4. Run the score model on the jointly corrupted (noisy_pos, noisy_ori).
      5. Loss = pos_dsm_loss + orientation_dsm_loss.

    v4b bug fix: v4b only corrupted positions, leaving orientations at their clean x0 values.
    The model therefore saw an inconsistent input (noisy positions, clean orientations), which
    meant orientation predictions received no regularisation and could drift during fine-tuning.
    We now corrupt BOTH and compute DSM loss on BOTH.
    """
    pos_sde = sdes["pos"]
    so3_sde = sdes["node_orientations"]
    assert isinstance(so3_sde, SO3SDE)

    # Build batch with positions and backbone frames
    batch = Batch.from_data_list([context_chemgraph]).to(device)
    batch = batch.replace(pos=x0_pos_nm, node_orientations=x0_orientations)

    # SO3SDE must run on CPU. Its IGSO3 lookup tables are loaded on CPU and the
    # series-expansion computations (igso3_expansion, dlog_igso3_expansion) are not
    # compatible with GPU placement. dpm_solver (called earlier for the PPFT rollout)
    # moves so3_sde to GPU as a side effect, so we explicitly move it back to CPU here.
    # All SO3SDE inputs are also moved to CPU; results are moved back to `device`.
    so3_sde.cpu()

    # Sample a random diffusion time; avoid very small t where sigma_t -> 0
    t = torch.empty(1, device=device).uniform_(0.05, 0.99)

    # ---- Position corruption (VP-SDE) ----
    alpha_t, sigma_t = pos_sde.mean_coeff_and_std(
        x=batch.pos, t=t, batch_idx=batch.batch,
    )
    pos_noise = torch.randn_like(batch.pos)
    noisy_pos = alpha_t * batch.pos + sigma_t * pos_noise

    # ---- Orientation corruption (SO3-SDE) ----
    # SO3SDE.sample_marginal(R_0, t, batch_idx) returns R_t = R_0 @ IGSO3(I, sigma_rot_t)
    # Inputs must be on CPU; result is moved back to device.
    # noisy_ori is still needed so the score model sees a consistent (noisy_pos, noisy_ori)
    # input — providing clean orientations alongside noisy positions would give the model
    # an unrealistic input distribution.
    noisy_ori = so3_sde.sample_marginal(
        x=batch.node_orientations.to("cpu"),
        t=t.to("cpu"),
        batch_idx=batch.batch.to("cpu"),
    ).to(device)  # (n_residues, 3, 3)

    # Build the corrupted batch with BOTH noisy positions and noisy orientations
    batch_noisy = batch.replace(pos=noisy_pos, node_orientations=noisy_ori)

    # ── Raw model prediction ─────────────────────────────────────────────────────
    # Call score_model directly to obtain raw network output, bypassing get_score()
    # post-processing. get_score() applies score scaling to orientations and divides
    # positions by sigma_t — operating in that post-processed space creates a
    # time-dependent mismatch vs the ground-truth score targets. Working in raw
    # output space matches the convention in Luca's DeltaFoldWrapper.training_step().
    raw_pred = score_model(batch_noisy, t)

    # ── Position DSM loss ─────────────────────────────────────────────────────────
    # The raw position output predicts -eps (negative noise), because the VP-SDE
    # score is s = -eps/sigma_t and the network is parameterised as:
    #   raw_pos = s * sigma_t = -eps
    # So MSE(raw_pred["pos"], -pos_noise) is the correct target.
    # (This is equivalent to v4b's predicted_noise = -score["pos"] * sigma_t after
    # substituting score["pos"] = raw_pos / sigma_t from get_score().)
    pos_dsm_loss = F.mse_loss(raw_pred["pos"], -pos_noise)

    # ── Orientation DSM loss — DISABLED in v5b ───────────────────────────────────
    # The v5 orientation loss was missing the `loss_scaled` weighting present in
    # Luca's reference implementation (lighting.py training_step, loss_scaled=True):
    #
    #   loss_ori = mse(pred, target).sum(dim=-1) / ori_scale**2
    #
    # Without this division, the loss is dominated by large-t samples where
    # ori_scaling is small and target_ori = gt_score / ori_scaling is large.
    # This trains backbone frames to match high-noise orientations while ignoring
    # low-noise (near t=0) orientations — exactly backwards for generation quality.
    # In v20, this produced steric clashes in EVERY generated structure.
    #
    # v5b disables the orientation loss entirely, reverting to position-DSM-only
    # (as in v4b, which produced only some clashes). The correctly weighted
    # orientation loss can be re-enabled in a future version once verified.

    # ── Combined DSM loss ─────────────────────────────────────────────────────────
    dsm_loss = pos_dsm_loss

    if torch.isnan(dsm_loss):
        logger.warning(f"NaN in DSM loss at t={t.item():.4f} — skipping this term.")
        return torch.tensor(0.0, device=device, requires_grad=False)

    return dsm_loss


