class FoldednessFineTuner(pl.LightningModule):
    """
    Fine-tunes the BioEmu score model to match experimental foldedness values.

    For each mutant in a batch:
      1. Load pre-cached embeddings and build a context ChemGraph.
      2. Run a short diffusion rollout to generate n_replications structures.
      3. Score each structure with ContactStateClassifier.
      4. Compute the unbiased squared-mean-error loss vs. the experimental target.
      5. Average the loss across mutants in the batch.
    """

    def __init__(
        self,
        score_model: torch.nn.Module,
        sdes: dict,
        state_classifier: ContactStateClassifier,
        lr: float = 1e-5,           # Low LR for fine-tuning
        weight_decay: float = 1e-2,
        n_replications: int = 8,    # Structures per mutant; minimum 2, paper used 2; more = lower variance, higher cost
        mid_t: float = 0.1,         # Rollout endpoint; 0.1 for reliable skip-to-x0 (v4b used 0.77)
        N_rollout: int = 30,        # Number of explicit denoising steps (more needed at lower mid_t)
        record_grad_steps: tuple = (28,),          # Last step only (0-indexed, default for N_rollout=30)
        trainable_components: list[str] = None, # I can now name the individual components of the model I want to train
        dsm_weight: float = 0.1,    # Weight for DSM regularisation loss (0.0 = PPFT only)
    ):
        super().__init__()
        self.save_hyperparameters(ignore=["score_model", "sdes", "state_classifier"])
        self.score_model = score_model
        self.sdes = sdes
        self.state_classifier = state_classifier
        self.lr = lr
        self.weight_decay = weight_decay
        self.n_replications = n_replications
        self.mid_t = mid_t
        self.N_rollout = N_rollout
        self.record_grad_steps = set(record_grad_steps)
        self.dsm_weight = dsm_weight

        # Validate that record_grad_steps are all valid 0-indexed step indices.
        # The DPM solver loop runs for i in range(N_rollout - 1), i.e. i = 0 .. N_rollout-2.
        # record_grad_steps values must be in range [0, N_rollout-2].
        valid_range = set(range(N_rollout - 1))
        invalid_steps = self.record_grad_steps - valid_range
        assert len(invalid_steps) == 0, (
            f"record_grad_steps contains indices {invalid_steps} that are outside the valid "
            f"range [0, {N_rollout - 2}] (0-indexed DPM solver loop with N_rollout={N_rollout}). "
            f"The DPM solver loop runs for i in range(N_rollout - 1) = range({N_rollout - 1}). "
            f"Each value in record_grad_steps must be a valid loop index."
        )

        # Components to train (everything else is frozen).
        # Names are matched as prefixes against model_nn.* parameter names.
        # Default: train only the last 2 transformer layers + diffusion head.
        _TRAINABLE_PREFIXES = set()
        for prefix in trainable_components:
            _TRAINABLE_PREFIXES.add(prefix)

        frozen, trainable = 0, 0
        for name, param in self.score_model.named_parameters():
            if any(name.startswith(p) for p in _TRAINABLE_PREFIXES):
                param.requires_grad = True
                trainable += param.numel()
            else:
                param.requires_grad = False
                frozen += param.numel()
        logger.info(
            f"Trainable components: {trainable_components}\n"
            f"  {trainable:,} trainable params, {frozen:,} frozen params."
        )

    def configure_optimizers(self):
        # Only pass parameters that require gradients to the optimizer.
        # Frozen parameters (requires_grad=False) are automatically excluded.
        trainable_params = [p for p in self.score_model.parameters() if p.requires_grad]
        return torch.optim.AdamW(
            trainable_params,
            lr=self.lr,
            weight_decay=self.weight_decay,
        )

    def _step(self, batch: list[dict], split: str) -> torch.Tensor:
        device = self.device
        total_ppft_loss = torch.tensor(0.0, device=device)
        total_dsm_loss = torch.tensor(0.0, device=device)
        n_dsm = 0  # track how many mutants contributed a DSM loss

        # Move state classifier to current device (no-op if already there)
        self.state_classifier.to(device)

        for item in batch:
            mutant_name = item["mutant_name"]
            sequence = item["sequence"]
            target_foldedness = item["target_foldedness"]

            # Load embeddings and build context ChemGraph
            context_cg = load_context_chemgraph(
                sequence=sequence,
                single_embeds_file=item["single_embeds_file"],
                pair_embeds_file=item["pair_embeds_file"],
            )

            # --- PPFT loss ---
            x0_pos_stack, state_scores = rollout_and_score(
                score_model=self.score_model,
                sdes=self.sdes,
                context_chemgraph=context_cg,
                n_replications=self.n_replications,
                mid_t=self.mid_t,
                N_rollout=self.N_rollout,
                record_grad_steps=self.record_grad_steps,
                device=device,
                sequence=sequence,
                state_classifier=self.state_classifier,
            )
            ppft_loss = compute_ppft_loss(
                state_scores=state_scores,
                target_state2_fraction=target_foldedness,
                n_replications=self.n_replications,
            )
            total_ppft_loss = total_ppft_loss + ppft_loss

            self.log(
                f"{split}/state_score_mean_{mutant_name}",
                state_scores.mean(),
                prog_bar=False,
                batch_size=1,
            )

            # --- DSM loss (only if structure library is available and dsm_weight > 0) ---
            if self.dsm_weight > 0.0 and item["structures_xtc"] is not None:
                library = get_structure_library(
                    xtc_path=item["structures_xtc"],
                    pdb_path=item["structures_pdb"],
                )
                # Sample one random structure (positions + backbone frames)
                x0_np, ori_np = library.sample()
                x0_pos = torch.tensor(x0_np, dtype=torch.float32, device=device)
                x0_ori = torch.tensor(ori_np, dtype=torch.float32, device=device)

                dsm_loss = compute_dsm_loss(
                    score_model=self.score_model,
                    sdes=self.sdes,
                    x0_pos_nm=x0_pos,
                    x0_orientations=x0_ori,
                    context_chemgraph=context_cg,
                    device=device,
                )
                total_dsm_loss = total_dsm_loss + dsm_loss
                n_dsm += 1

        # Average losses over batch
        total_ppft_loss = total_ppft_loss / len(batch)
        total_dsm_loss = total_dsm_loss / n_dsm if n_dsm > 0 else total_dsm_loss

        if torch.isnan(total_ppft_loss):
            logger.warning(f"NaN in PPFT loss at {split} step.")
        if torch.isnan(total_dsm_loss):
            logger.warning(f"NaN in DSM loss at {split} step.")

        total_loss = total_ppft_loss + self.dsm_weight * total_dsm_loss

        # on_epoch=True, on_step=False: aggregate all steps within an epoch before logging.
        # This makes train and val loss curves directly comparable (val is always epoch-aggregated
        # by Lightning by default). Without this, train losses are logged per step (1 mutant at a
        # time), appearing noisy/flat relative to the smooth epoch-averaged val curve.
        self.log(f"{split}/ppft_loss", total_ppft_loss, prog_bar=False, batch_size=len(batch),
                 on_epoch=True, on_step=False)
        self.log(f"{split}/dsm_loss", total_dsm_loss, prog_bar=False, batch_size=len(batch),
                 on_epoch=True, on_step=False)
        self.log(f"{split}/loss", total_loss, prog_bar=True, batch_size=len(batch),
                 on_epoch=True, on_step=False)
        self.log(f"{split}/loss_abs", torch.abs(total_loss), prog_bar=False, batch_size=len(batch),
                 on_epoch=True, on_step=False)
        return total_loss

    def training_step(self, batch: list[dict], batch_idx: int) -> torch.Tensor:
        return self._step(batch, "train")

    def validation_step(self, batch: list[dict], batch_idx: int) -> torch.Tensor:
        return self._step(batch, "val")


