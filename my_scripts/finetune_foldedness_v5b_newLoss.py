"""
Fine-tuning script for BioEmu score model on experimental foldedness data.
Version 5: ContactStateClassifier PPFT loss + Denoising Score Matching (DSM) with orientation regularisation.

Changes from v4b:
  - Replaces the 3-pair sigmoid foldedness score with ContactStateClassifier
    (29-contact differential CA-CA metric from contact_state_loss.py).
  - Fixes mid_t default from 0.77 to 0.1 (reduced training/inference mismatch):
    at mid_t=0.77 the skip-to-x0 prediction from a highly noisy intermediate is
    poorly correlated with the final structure; at mid_t=0.1 the prediction is much
    more reliable. Setting mid_t=0.0 triggers full denoising (no skip step).
  - Fixes record_grad_steps to be correctly 0-indexed and defaults to the last 3
    steps of the DPM solver loop (range(N_rollout-1)).
  - DSM now uses pruned ensembles (samples_pruned_v2.xtc, pruned by
    prune_trajectory_by_contact_state.py to match the experimental state
    distribution before DSM training).
  - DSM loss now includes orientation regularisation via SO3SDE corruption and
    SO3 score matching, in addition to position DSM.

Approach:
- For each mutant, pre-computed ColabFold embeddings are loaded from cache (no internet needed at runtime).
- PPFT loss: A short diffusion rollout generates an ensemble of structures. Each is scored
  by the ContactStateClassifier (differentiable). The loss is an unbiased estimate of
  (mean_state_score - target_foldedness)^2.
- DSM loss: A structure is randomly sampled from a pre-generated (pruned) ensemble for the same
  mutant, corrupted to a random noise level t via the forward SDE (both positions and orientations),
  and the score model is trained to denoise it back. This regularises against steric clashes and
  structural unrealism that can arise from training on PPFT alone.
- Total loss: L = L_PPFT + dsm_weight * L_DSM
- Only the score model is trained; embeddings are fixed.

Data requirements:
- A CSV with columns "mutant_name" and "percent_folded"
- A flat directory of pre-computed ColabFold embeddings produced by get_colabfold_embeds(),
  containing files named {sha256(sequence)}_single.npy and {sha256(sequence)}_pair.npy.
- A structures directory containing one subdirectory per mutant named KRAS_{mutant_name}/,
  each holding samples_pruned_v2.xtc and topology.pdb (generated by run_bioemu_batch.py
  then pruned by prune_trajectory_by_contact_state.py).

Usage:
    python finetune_foldedness_v5_newLoss.py \
        <embeds_dir> <foldedness_csv> <output_dir> <sequence_map> \
        --structures_dir /path/to/pregenerated/structures \
        --dsm_weight 0.1 \
        --cache_so3 /path/to/so3_cache \
        --gpus 1
"""

